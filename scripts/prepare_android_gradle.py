#!/usr/bin/env python3
"""Prepare a Flutter-generated Android scaffold for share_plus 13.x.

The Android directory is passed explicitly by CI. Both Groovy and Kotlin DSL
are supported. Missing files produce actionable diagnostics instead of a
cryptic FileNotFoundError from pathlib.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

MIN_AGP = "8.12.1"
MIN_KOTLIN = "2.2.0"
MIN_GRADLE = "8.13"


def version_tuple(value: str) -> tuple[int, ...]:
    nums = [int(part) for part in re.findall(r"\d+", value)[:3]]
    return tuple(nums + [0] * (3 - len(nums)))


def first_existing(paths: list[Path], label: str) -> Path:
    for path in paths:
        if path.is_file():
            return path
    searched = "\n".join(f"  - {p}" for p in paths)
    raise FileNotFoundError(f"Could not find {label}. Looked for:\n{searched}")


def patch_plugin(text: str, plugin_id: str, minimum: str) -> tuple[str, bool, bool]:
    # Matches both: id "x" version "y" and id("x") version "y".
    pattern = re.compile(
        r'(\bid\s*\(?\s*["\']' + re.escape(plugin_id) +
        r'["\']\s*\)?\s+version\s+["\'])([^"\']+)(["\'])'
    )
    found = False
    changed = False

    def repl(match: re.Match[str]) -> str:
        nonlocal found, changed
        found = True
        current = match.group(2)
        if version_tuple(current) < version_tuple(minimum):
            changed = True
            return match.group(1) + minimum + match.group(3)
        return match.group(0)

    return pattern.sub(repl, text), found, changed


def patch_min_sdk(text: str, gradle_file: Path) -> tuple[str, bool]:
    # Flutter templates have used these forms in Groovy and Kotlin DSL.
    patterns = [
        (r'(?m)(\bminSdk\s*=\s*)flutter\.minSdkVersion\b', r'\g<1>24'),
        (r'(?m)(\bminSdkVersion\s+)flutter\.minSdkVersion\b', r'\g<1>24'),
        (r'(?m)(\bminSdk\s*=\s*)\d+\b', r'\g<1>24'),
        (r'(?m)(\bminSdkVersion\s+)\d+\b', r'\g<1>24'),
    ]
    for pattern, replacement in patterns:
        updated, count = re.subn(pattern, replacement, text, count=1)
        if count:
            return updated, updated != text

    # Do not silently build a plugin-incompatible app if the template changes.
    raise RuntimeError(
        f"Could not find minSdk declaration in {gradle_file}. "
        "Expected minSdk = flutter.minSdkVersion or minSdkVersion flutter.minSdkVersion."
    )


def main() -> int:
    if len(sys.argv) > 1:
        android_dir = Path(sys.argv[1]).resolve()
    else:
        android_dir = Path(__file__).resolve().parents[1] / "android"

    if not android_dir.is_dir():
        raise FileNotFoundError(
            f"Android scaffold directory does not exist: {android_dir}. "
            "Run `flutter create --platforms=android` before this script."
        )

    settings_file = first_existing(
        [android_dir / "settings.gradle.kts", android_dir / "settings.gradle"],
        "Gradle settings file",
    )
    app_gradle = first_existing(
        [android_dir / "app" / "build.gradle.kts", android_dir / "app" / "build.gradle"],
        "app Gradle build file",
    )
    wrapper_file = android_dir / "gradle" / "wrapper" / "gradle-wrapper.properties"
    if not wrapper_file.is_file():
        raise FileNotFoundError(
            f"Gradle wrapper properties are missing: {wrapper_file}. "
            "Use the Android directory generated by Flutter, not a hand-made folder."
        )

    settings = settings_file.read_text(encoding="utf-8")
    changes: list[str] = []
    for plugin, minimum in (
        ("com.android.application", MIN_AGP),
        ("org.jetbrains.kotlin.android", MIN_KOTLIN),
        ("kotlin-android", MIN_KOTLIN),
    ):
        settings, found, changed = patch_plugin(settings, plugin, minimum)
        # Flutter's generated template must declare the Android application plugin.
        if plugin == "com.android.application" and not found:
            raise RuntimeError(
                f"Could not locate the com.android.application plugin version in {settings_file}. "
                "The generated Flutter Gradle template may have changed."
            )
        if changed:
            changes.append(f"Updated {plugin} to {minimum}")
    settings_file.write_text(settings, encoding="utf-8")

    app_text = app_gradle.read_text(encoding="utf-8")
    app_text, min_changed = patch_min_sdk(app_text, app_gradle)
    if min_changed:
        changes.append("Set Android minSdk to 24 (required by share_plus 13.x)")
    app_gradle.write_text(app_text, encoding="utf-8")

    wrapper = wrapper_file.read_text(encoding="utf-8")
    match = re.search(r"distributionUrl=.*?gradle-([0-9.]+)-(all|bin)\.zip", wrapper)
    if not match:
        raise RuntimeError(
            f"Could not parse Gradle distributionUrl in {wrapper_file}: "
            "expected gradle-X.Y-all.zip or gradle-X.Y-bin.zip."
        )
    gradle_version = match.group(1)
    agp_match = re.search(
        r'\bid\s*\(?\s*["\']com\.android\.application["\']\s*\)?\s+version\s+["\']([^"\']+)',
        settings,
    )
    if not agp_match:
        raise RuntimeError(f"Could not determine AGP version in {settings_file}.")
    agp_version = agp_match.group(1)
    agp_major = version_tuple(agp_version)[0]
    gradle_tuple = version_tuple(gradle_version)
    desired_gradle = gradle_version

    # share_plus requires Gradle >= 8.13; AGP 8.x must not be paired with Gradle 9.x.
    if agp_major == 8 and (gradle_tuple[0] > 8 or gradle_tuple < version_tuple(MIN_GRADLE)):
        desired_gradle = MIN_GRADLE
    elif agp_major >= 9 and gradle_tuple < version_tuple("9.1"):
        desired_gradle = "9.1"
    elif agp_major < 8:
        raise RuntimeError(f"Unsupported Android Gradle Plugin version: {agp_version}")

    if desired_gradle != gradle_version:
        wrapper = re.sub(
            r"gradle-[0-9.]+-(all|bin)\.zip",
            lambda m: f"gradle-{desired_gradle}-{m.group(1)}.zip",
            wrapper,
            count=1,
        )
        changes.append(f"Aligned Gradle wrapper to {desired_gradle} for AGP {agp_version}")
    wrapper_file.write_text(wrapper, encoding="utf-8")

    if not (android_dir / "gradlew").is_file():
        raise FileNotFoundError(f"Gradle launcher is missing: {android_dir / 'gradlew'}")

    print(f"Android directory: {android_dir}")
    print(f"Settings file: {settings_file.name}")
    print(f"App Gradle file: {app_gradle.relative_to(android_dir)}")
    print(f"Android Gradle Plugin: {agp_version}")
    print(f"Gradle wrapper: {desired_gradle}")
    for change in changes:
        print(f"- {change}")
    print("Android Gradle preparation completed.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"PREPARE_ANDROID_GRADLE_ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1)
